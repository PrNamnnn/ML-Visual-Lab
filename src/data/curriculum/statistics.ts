import type { ModuleDef, TopicDef } from "@/types/curriculum";
import { distributionById } from "@/lib/statistics/distributions";

/** Build a complete distribution topic from the distribution registry plus moment formulas. */
function dist(slug: string, id: string, meanTex: string, varTex: string, extra: { story: string; why: string; usedIn: string[]; keywords: string[]; app: { title: string; body: string }; related?: string[]; special?: string[] }): TopicDef {
  const d = distributionById(id)!;
  return {
    slug,
    title: d.name.replace(" (marginal)", "") + (d.name.includes("distribution") ? "" : " Distribution"),
    summary: d.notes,
    difficulty: ["chi-square", "student-t", "f", "gamma", "beta", "weibull", "multinomial"].includes(id) ? "intermediate" : "beginner",
    keywords: [d.name.toLowerCase(), d.kind === "discrete" ? "pmf" : "pdf", "cdf", ...extra.keywords],
    prerequisites: [d.kind === "discrete" ? "statistics/random-variables" : "calculus/integration-probability"],
    related: extra.related ?? ["statistics/random-variables"],
    content: {
      definition: extra.story,
      why: extra.why,
      usedIn: extra.usedIn,
      visual: { id: "distribution", props: { id }, caption: `Adjust the parameters, switch between ${d.kind === "discrete" ? "PMF" : "PDF"} and CDF, click to query P(X ≤ x), and draw samples to compare the histogram with the theory.` },
      formulas: [
        { label: d.kind === "discrete" ? "Probability mass function" : "Probability density function", tex: d.formula, explanation: `Support: ${d.support.replace(/\\[a-z]+/g, "").replace(/[{}]/g, "")}.` },
        { label: "Mean", tex: `E[X]=${meanTex}`, explanation: "The long-run average of samples." },
        { label: "Variance", tex: `\\operatorname{Var}(X)=${varTex}`, explanation: "Expected squared deviation from the mean." },
      ],
      specialCases: extra.special,
      applications: [{ title: "In machine learning", body: d.mlUse }, extra.app],
    },
  };
}

