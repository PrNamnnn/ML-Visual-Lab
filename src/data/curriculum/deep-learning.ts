import { activations, losses } from "@/lib/nn";

const actTopic = (id: string, extra: { why: string; usedIn: string[]; keywords?: string[] }): TopicDef => {
  const a = activations.find((x) => x.id === id)!;
  return {
    slug: `${id}-activation`,
    title: `${a.name} Activation`,
    summary: a.notes,
    difficulty: "beginner",
    keywords: [a.name.toLowerCase(), "activation function", ...(extra.keywords ?? [])],
    prerequisites: ["deep-learning/artificial-neuron"],
    related: ["deep-learning/activation-functions", "deep-learning/vanishing-gradients"],
    content: {
      definition: `${a.name}: ${a.notes}`,
      why: extra.why,
      usedIn: extra.usedIn,
      visual: { id: "activation", props: { id }, caption: "Blue: the function. Pink dashed: its derivative — the factor multiplying gradients that flow backward through this unit." },
      formulas: [
        { label: "Function", tex: a.tex, explanation: `Output range: ${a.range.replace(/\\[a-z]+/g, (m) => (m === "\\infty" ? "∞" : m === "\\alpha" ? "α" : m === "\\lambda" ? "λ" : m === "\\approx" ? "≈" : ""))}.` },
        { label: "Derivative", tex: a.dtex, explanation: "Used by backpropagation at every unit." },
      ],
      applications: [{ title: "Gradient flow", body: "Where the derivative is near zero (saturation, or the negative side of ReLU) almost no learning signal passes through the unit." }],
    },
  };
};

const lossTopic = (id: string, slug: string, extra: { why: string; usedIn: string[]; keywords?: string[] }): TopicDef => {
  const l = losses.find((x) => x.id === id)!;
  return {
    slug,
    title: l.name,
    summary: l.notes.split(". ")[0] + ".",
    difficulty: ["kl", "contrastive", "triplet", "focal"].includes(id) ? "intermediate" : "beginner",
    keywords: [l.name.toLowerCase(), "loss function", ...(extra.keywords ?? [])],
    prerequisites: ["deep-learning/loss-functions"],
    related: ["deep-learning/loss-functions"],
    content: {
      definition: l.notes,
      why: extra.why,
      usedIn: extra.usedIn,
      visual: { id: "loss", props: { id }, caption: "Drag the prediction and watch the loss and its gradient change." },
      formulas: [{ label: l.name, tex: l.tex, explanation: l.notes.split(". ")[0] + "." }],
      applications: [{ title: "Gradient shape matters", body: "The derivative of the loss is the error signal that starts backpropagation; its shape decides how hard the model is pushed on easy versus hard examples." }],
    },
  };
};

