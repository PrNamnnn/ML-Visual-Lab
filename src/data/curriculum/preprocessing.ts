import type { ModuleDef, TopicDef, TopicContent } from "@/types/curriculum";
import { transformById, scalers } from "@/lib/transformations";

function transformTopic(slug: string, id: string, extra: { why: string; usedIn: string[]; keywords: string[]; worked?: TopicContent["worked"]; difficulty?: "beginner" | "intermediate" | "advanced"; related?: string[] }): TopicDef {
  const t = transformById(id)!;
  return {
    slug,
    title: t.name,
    summary: t.intuition.split(". ")[0] + ".",
    difficulty: extra.difficulty ?? "beginner",
    keywords: [t.name.toLowerCase(), "transformation", "skewness", ...extra.keywords],
    prerequisites: ["statistics/expected-value-variance"],
    related: extra.related ?? ["preprocessing/feature-scaling", "preprocessing/box-cox-transformation"],
    content: {
      definition: t.intuition,
      why: extra.why,
      usedIn: extra.usedIn,
      visual: { id: "transform-lab", props: { id }, caption: "Original (blue) versus transformed (pink) distribution with skewness before and after. Change the dataset to see how zeros and negatives are handled." },
      formulas: [{ label: "Transformation", tex: t.formula, explanation: t.intuition }],
      assumptions: [t.zeroNegative],
      limitations: [t.limitations],
      worked: extra.worked,
      applications: [{ title: "Use cases", body: t.useCases }, { title: "Fit on training data only", body: "Any parameter (λ, shift, bins, ranks) must be learned on the training split and re-applied unchanged to validation, test and production data to avoid leakage." }],
    },
  };
}

function scalerTopic(slug: string, id: string, extra: { why: string; usedIn: string[]; keywords: string[]; when: string }): TopicDef {
  const s = scalers.find((x) => x.id === id)!;
  return {
    slug,
    title: s.name,
    summary: s.description.split(". ")[0] + ".",
    difficulty: "beginner",
    keywords: [s.name.toLowerCase(), "feature scaling", "normalization", ...extra.keywords],
    related: ["preprocessing/feature-scaling"],
    content: {
      definition: s.description,
      why: extra.why,
      usedIn: extra.usedIn,
      visual: { id: "scaling-lab", props: { method: id }, caption: "Original versus scaled feature. Toggle outliers to see which scalers are robust." },
      formulas: [{ label: s.name, tex: s.formula, explanation: extra.when }],
      limitations: ["Linear scaling never changes the shape of a distribution (skewness and outliers remain)."],
      applications: [{ title: "Pipeline hygiene", body: "Fit the scaler on training data (e.g. sklearn's fit on X_train, transform on X_test) so test statistics never leak into training." }],
    },
  };
}

